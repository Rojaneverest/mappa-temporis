// Territory over time (decision 57): for every lane the Atlas links to Cliopatria polities, the
// area it held each decade, summed from the committed Atlas files. The build turns this into lane
// width, so empires swell at their height and thin in decline.
//
//   node scripts/atlas/power.ts            (after `pnpm atlas`; writes content/power.json)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoArea } from 'd3-geo';
import { feature } from 'topojson-client';
import type { Feature, FeatureCollection, Geometry } from 'geojson';
import type { GeometryCollection, Topology } from 'topojson-specification';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const ATLAS = join(ROOT, 'apps/explorer/public/atlas');
const KM2_PER_STERADIAN = 6371 ** 2;
const STEP = 10;

interface Props { n: string; f: number; t: number; l?: string }
const index = JSON.parse(readFileSync(join(ATLAS, 'world.atlas.json'), 'utf8')) as { chunks: { from: number; to: number; url: string }[] };
/** lane → decade → km² */
const area = new Map<string, Map<number, number>>();
for (const c of index.chunks) {
  const topo = JSON.parse(readFileSync(join(ATLAS, 'world', c.url), 'utf8')) as Topology<{ polities: GeometryCollection<Props> }>;
  const polities = (feature(topo, topo.objects.polities) as FeatureCollection<Geometry, Props>).features as Feature<Geometry, Props>[];
  for (const p of polities) {
    const lane = p.properties.l;
    if (!lane) continue;
    const km2 = geoArea(p) * KM2_PER_STERADIAN;
    // Each chunk holds the polities alive in its own years; count only those years so nothing doubles.
    const a = Math.max(c.from, p.properties.f), b = Math.min(c.to, p.properties.t);
    for (let y = Math.ceil(a / STEP) * STEP; y <= b; y += STEP) {
      const row = area.get(lane) ?? new Map<number, number>();
      row.set(y, (row.get(y) ?? 0) + km2);
      area.set(lane, row);
    }
  }
}
const out: Record<string, [number, number][]> = {};
for (const [lane, row] of [...area].sort((a, b) => a[0].localeCompare(b[0]))) {
  out[lane] = [...row].sort((a, b) => a[0] - b[0]).map(([y, km2]) => [y, Math.round(km2 / 1000) * 1000]);
}
writeFileSync(join(ROOT, 'content/power.json'), JSON.stringify({ note: 'Generated by scripts/atlas/power.ts from the Cliopatria Atlas files (CC BY 4.0): km² held by each lane every 10 years.', step: STEP, lanes: out }) + '\n');
const peaks = Object.entries(out).map(([l, r]) => [l, Math.max(...r.map((q) => q[1]))] as const).sort((a, b) => b[1] - a[1]);
console.log(`✓ ${peaks.length} lanes with territory; largest: ${peaks.slice(0, 8).map(([l, k]) => `${l} ${(k / 1e6).toFixed(1)}M km²`).join(' · ')}`);
